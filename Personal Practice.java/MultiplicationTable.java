public class MultiplicationTable{
	public static void main(String...args){
	
	int result = 0;
for(int row = 1; row <= 3; row++){
		
	for(int column = 1; column <= 3; column++){

		System.out.println(row *  + " x " + column + " = " + result);
		result++;
}	

System.out.println();

}











}









}